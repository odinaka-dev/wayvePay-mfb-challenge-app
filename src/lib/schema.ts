import * as z from "zod";

import {
  ACCOUNT_NUMBER_PATTERN,
  MAX_TRANSFER_MINOR,
  MIN_TRANSFER_MINOR,
} from "@/config/transfer";

import { formatMinor, parseAmountToMinor } from "./money";

/** First problem with a typed amount, so the user sees one clear message at a time. */
export function amountError(value: string): string | undefined {
  if (!value.trim()) return "Enter an amount";
  const minor = parseAmountToMinor(value);
  if (minor === null) return "Enter a valid amount with up to 2 decimal places";
  if (minor <= 0) return "Amount must be more than ₦0";
  if (minor < MIN_TRANSFER_MINOR) return `The minimum transfer is ${formatMinor(MIN_TRANSFER_MINOR)}`;
  if (minor > MAX_TRANSFER_MINOR) return `The maximum transfer is ${formatMinor(MAX_TRANSFER_MINOR)}`;
  return undefined;
}

// What the user fills in. The amount is typed in naira and converted to kobo on submit;
// the idempotency key is generated by the app, not entered.
export const transferSchema = z.object({
  recipientBankCode: z.string().min(1, { message: "Select a bank" }),
  recipientAccountNumber: z
    .string()
    .regex(ACCOUNT_NUMBER_PATTERN, { message: "Enter a 10 digit account number" }),
  amount: z.string().superRefine((value, ctx) => {
    const message = amountError(value);
    if (message) ctx.addIssue({ code: "custom", message });
  }),
  narration: z
    .string()
    .max(100, { message: "Keep the note under 100 characters" })
    .optional(),
});

export type transferFormData = z.infer<typeof transferSchema>;
